import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { extractBoundedZipArchive } from "@boltpocket/project-shell-extras/zip";
import { zipSync } from "fflate";
import { format } from "prettier";

import { H5_RUNTIME_BUNDLE } from "../src/infrastructure/browser/h5-runtime-bundle.generated.ts";
import {
  H5_RUNTIME_BUNDLE_LIMITS,
  validateH5RuntimeBundleEntries,
} from "../src/infrastructure/browser/h5-runtime-bundle.ts";
import {
  H5_RUNTIME_ASSETS,
  h5RuntimeCacheFileName,
  normalizeH5RuntimeMimeType,
} from "../src/infrastructure/browser/h5-runtime-registry.ts";
import { resolveH5RuntimeSource } from "../src/infrastructure/browser/h5-runtime-source-policy.ts";

const appRoot = fileURLToPath(new URL("..", import.meta.url));
const archivePath = join(appRoot, "assets", "h5-runtimes-v1.zip");
const generatedPath = join(
  appRoot,
  "src",
  "infrastructure",
  "browser",
  "h5-runtime-bundle.generated.ts",
);

function digest(bytes: Uint8Array) {
  return createHash("sha256").update(bytes).digest("hex");
}

async function verifiedDownload(
  asset: (typeof H5_RUNTIME_ASSETS)[keyof typeof H5_RUNTIME_ASSETS],
) {
  const resolved = await resolveH5RuntimeSource(
    asset,
    undefined,
    async (source) => {
      const response = await fetch(source.url, {
        headers: {
          Accept: "text/javascript, application/javascript",
          "Accept-Encoding": "identity",
        },
        redirect: "follow",
        signal: AbortSignal.timeout(30_000),
      });
      if (!response.ok) throw new Error(`HTTP ${response.status}`);
      const mimeType = normalizeH5RuntimeMimeType(
        response.headers.get("content-type"),
      );
      if (
        mimeType &&
        !asset.allowedMimeTypes.some(
          (allowed) => allowed.toLowerCase() === mimeType,
        )
      ) {
        throw new Error("unexpected MIME type");
      }
      const bytes = new Uint8Array(await response.arrayBuffer());
      if (
        bytes.byteLength !== asset.byteLength ||
        digest(bytes) !== asset.sha256
      ) {
        throw new Error("integrity mismatch");
      }
      return bytes;
    },
  );
  return resolved.value;
}

async function verifyArchive(archive: Uint8Array) {
  assert.ok(
    archive.byteLength <= H5_RUNTIME_BUNDLE_LIMITS.maxArchiveBytes,
    "H5 runtime ZIP is too large",
  );
  const entries = extractBoundedZipArchive(archive, H5_RUNTIME_BUNDLE_LIMITS);
  await validateH5RuntimeBundleEntries(entries, async (bytes) => digest(bytes));
}

async function check() {
  const archive = new Uint8Array(readFileSync(archivePath));
  assert.equal(archive.byteLength, H5_RUNTIME_BUNDLE.byteLength);
  assert.equal(digest(archive), H5_RUNTIME_BUNDLE.sha256);
  await verifyArchive(archive);
  console.log(
    JSON.stringify({
      type: "h5-runtime-offline-bundle",
      passed: true,
      byteLength: archive.byteLength,
      assetCount: Object.keys(H5_RUNTIME_ASSETS).length,
    }),
  );
}

async function build() {
  const files: Record<string, Uint8Array> = {};
  for (const asset of Object.values(H5_RUNTIME_ASSETS)) {
    files[h5RuntimeCacheFileName(asset)] = await verifiedDownload(asset);
  }
  const archive = zipSync(
    Object.fromEntries(
      Object.entries(files)
        .sort(([left], [right]) => left.localeCompare(right, "en"))
        .map(([name, bytes]) => [
          name,
          [bytes, { level: 9, mtime: new Date(2020, 0, 1) }],
        ]),
    ),
  );
  await verifyArchive(archive);
  const sha256 = digest(archive);
  const generated = await format(
    [
      "// Generated by app/scripts/build-h5-runtime-bundle.ts. Do not edit by hand.",
      "export const H5_RUNTIME_BUNDLE = Object.freeze({",
      "  schema: 1,",
      '  assetFileName: "h5-runtimes-v1.zip",',
      `  byteLength: ${archive.byteLength},`,
      `  sha256: ${JSON.stringify(sha256)},`,
      "} as const);",
      "",
    ].join("\n"),
    { parser: "typescript" },
  );
  mkdirSync(dirname(archivePath), { recursive: true });
  writeFileSync(archivePath, archive);
  writeFileSync(generatedPath, generated);
  console.log(
    JSON.stringify({
      type: "h5-runtime-offline-bundle",
      written: true,
      byteLength: archive.byteLength,
      sha256,
      assetCount: Object.keys(files).length,
    }),
  );
}

void (process.argv.includes("--check") ? check() : build());
