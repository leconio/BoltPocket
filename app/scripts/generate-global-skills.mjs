import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { format } from "prettier";

const appRoot = fileURLToPath(new URL("..", import.meta.url));
const skillsRoot = path.join(appRoot, "skills");
const outputPath = path.join(
  appRoot,
  "src",
  "domain",
  "global-skills.generated.ts",
);
const allowedFrontmatter = new Set(["name", "description"]);
const localizedSources = [
  { locale: "zh-CN", filename: "SKILL.md", variableName: "zhCNSkillDocuments" },
  { locale: "en", filename: "SKILL.en.md", variableName: "enSkillDocuments" },
];

function scalar(value, filePath, field) {
  const trimmed = value.trim();
  if (!trimmed) throw new Error(`${filePath}: ${field} cannot be empty`);
  if (trimmed.startsWith('"')) {
    const parsed = JSON.parse(trimmed);
    if (typeof parsed !== "string") {
      throw new Error(`${filePath}: ${field} must be a string`);
    }
    return parsed;
  }
  return trimmed;
}

function parseSkill(filePath, expectedId) {
  const source = readFileSync(filePath, "utf8").replace(/\r\n?/gu, "\n");
  const match = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/u.exec(source);
  if (!match) throw new Error(`${filePath}: invalid Skill frontmatter`);
  const frontmatter = {};
  for (const line of match[1].split("\n")) {
    const separator = line.indexOf(":");
    if (separator <= 0)
      throw new Error(`${filePath}: invalid frontmatter line`);
    const key = line.slice(0, separator).trim();
    if (!allowedFrontmatter.has(key) || Object.hasOwn(frontmatter, key)) {
      throw new Error(`${filePath}: unsupported or duplicate field ${key}`);
    }
    frontmatter[key] = scalar(line.slice(separator + 1), filePath, key);
  }
  if (
    !frontmatter.name ||
    frontmatter.name.length > 64 ||
    !/^[a-z0-9]+(?:-[a-z0-9]+)*$/u.test(frontmatter.name)
  ) {
    throw new Error(`${filePath}: invalid Skill name`);
  }
  if (frontmatter.name !== expectedId) {
    throw new Error(
      `${filePath}: Skill name must match its directory (${expectedId})`,
    );
  }
  if (!frontmatter.description) {
    throw new Error(`${filePath}: description is required`);
  }
  const content = match[2].trim();
  const heading = /^#\s+(.+)$/mu.exec(content)?.[1]?.trim();
  if (!heading) throw new Error(`${filePath}: one H1 display name is required`);
  return {
    id: frontmatter.name,
    name: heading,
    description: frontmatter.description,
    content,
    source: path.relative(appRoot, filePath).split(path.sep).join("/"),
  };
}

const skillDirectories = readdirSync(skillsRoot, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort((left, right) => left.localeCompare(right, "en"));

const documentsByLocale = Object.fromEntries(
  localizedSources.map(({ locale, filename }) => [
    locale,
    skillDirectories.map((id) =>
      parseSkill(path.join(skillsRoot, id, filename), id),
    ),
  ]),
);

function generatedDocuments(documents) {
  return documents
    .map((document) =>
      [
        "  {",
        `    id: ${JSON.stringify(document.id)},`,
        `    name: ${JSON.stringify(document.name)},`,
        `    description: ${JSON.stringify(document.description)},`,
        `    content: ${JSON.stringify(document.content)},`,
        `    source: ${JSON.stringify(document.source)},`,
        "  },",
      ].join("\n"),
    )
    .join("\n");
}

const documentDeclarations = localizedSources
  .map(({ locale, variableName }) =>
    [
      `const ${variableName} = [`,
      generatedDocuments(documentsByLocale[locale]),
      "] as const;",
    ].join("\n"),
  )
  .join("\n");

const messageKeys = skillDirectories
  .map((id) =>
    [
      `  ${JSON.stringify(id)}: {`,
      `    name: ${JSON.stringify(`library.builtinSkill.${id}.name`)},`,
      `    description: ${JSON.stringify(`library.builtinSkill.${id}.description`)},`,
      `    content: ${JSON.stringify(`library.builtinSkill.${id}.content`)},`,
      "  },",
    ].join("\n"),
  )
  .join("\n");

function generatedMessages(variableName) {
  return skillDirectories
    .map((id, index) =>
      [
        `    ${JSON.stringify(`library.builtinSkill.${id}.name`)}: ${variableName}[${index}].name,`,
        `    ${JSON.stringify(`library.builtinSkill.${id}.description`)}: ${variableName}[${index}].description,`,
        `    ${JSON.stringify(`library.builtinSkill.${id}.content`)}: ${variableName}[${index}].content,`,
      ].join("\n"),
    )
    .join("\n");
}

const unformatted = [
  "// Generated by app/scripts/generate-global-skills.mjs. Do not edit by hand.",
  documentDeclarations,
  "export const generatedGlobalSkillDocumentsByLocale = {",
  '  "zh-CN": zhCNSkillDocuments,',
  "  en: enSkillDocuments,",
  "} as const;",
  "export const generatedGlobalSkillDocuments = zhCNSkillDocuments;",
  "export const generatedGlobalSkillMessageKeysById = {",
  messageKeys,
  "} as const;",
  'type GlobalSkillMessageField = "name" | "description" | "content";',
  "export type GeneratedGlobalSkillMessageKey =",
  "  (typeof generatedGlobalSkillMessageKeysById)[keyof typeof generatedGlobalSkillMessageKeysById][GlobalSkillMessageField];",
  "export const generatedGlobalSkillMessagesByLocale = {",
  '  "zh-CN": {',
  generatedMessages("zhCNSkillDocuments"),
  "  },",
  "  en: {",
  generatedMessages("enSkillDocuments"),
  "  },",
  "} as const satisfies Readonly<",
  '  Record<"zh-CN" | "en", Record<GeneratedGlobalSkillMessageKey, string>>',
  ">;",
  "",
].join("\n");
const generated = await format(unformatted, { parser: "typescript" });

if (process.argv.includes("--check")) {
  const current = readFileSync(outputPath, "utf8");
  if (current !== generated) {
    throw new Error("Global Skill catalog is stale. Run pnpm skills:generate.");
  }
} else {
  writeFileSync(outputPath, generated);
}
