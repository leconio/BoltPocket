"""Verify embedded Metal bytes follow backdated source changes after reconfigure."""
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import tempfile
from ios_tools import ninja

source = Path("packages/expo-bolt-runtime/cpp/llama/ggml/src")
output = Path("build/metal-embed-regression")
output.mkdir(parents=True, exist_ok=True)
def verify(temporary):
    root = Path(temporary).resolve()
    shutil.copytree(source / "ggml-metal", root / "ggml-metal")
    shutil.copyfile(source / "ggml-common.h", root / "ggml-common.h")
    (root / "stub.cpp").write_text("int bolt_embed_fixture = 0;\n")
    (root / "CMakeLists.txt").write_text('''cmake_minimum_required(VERSION 3.22)
project(MetalEmbedFixture LANGUAGES C CXX)
function(ggml_add_backend_library target)
  add_library(${target} STATIC "${PROJECT_SOURCE_DIR}/stub.cpp")
endfunction()
set(GGML_METAL_EMBED_LIBRARY ON)
add_subdirectory(ggml-metal)
''')
    cmake = shutil.which("cmake") or "/opt/homebrew/bin/cmake"
    ninja_bin, ninja_receipt = ninja()
    configure = [cmake, "-S", str(root), "-B", str(root / "build"), "-G", "Ninja",
                 "-DCMAKE_MAKE_PROGRAM=" + ninja_bin]
    build = [cmake, "--build", str(root / "build"), "--parallel", "2"]
    with (output / "build.log").open("w") as log:
        for command in [configure, build]:
            subprocess.run(command, stdout=log, stderr=subprocess.STDOUT, check=True)
        for relative, marker in [
            ("ggml-metal/kernels/mul_mv.metal", "BOLT_BACKDATED_KERNEL"),
            ("ggml-metal/kernels/common.h", "BOLT_BACKDATED_SHARED_HEADER"),
        ]:
            changed = root / relative
            original = changed.read_bytes()
            changed.write_bytes(original + ("\n// " + marker + "\n").encode())
            os.utime(changed, (946684800, 946684800))
            for command in [configure, build]:
                subprocess.run(command, stdout=log, stderr=subprocess.STDOUT, check=True)
            embedded = root / "build/ggml-metal/autogenerated/ggml-metal-embed-mul_mv.metal"
            archive = root / "build/ggml-metal/libggml-metal.a"
            assert marker.encode() in embedded.read_bytes(), "Stale embedded source"
            assert marker.encode() in archive.read_bytes(), "Stale archive embedding"
            assert embedded.read_bytes() in archive.read_bytes(), "Archive differs from generated shader"
            changed.write_bytes(original)
            os.utime(changed, (946684800, 946684800))
            for command in [configure, build]:
                subprocess.run(command, stdout=log, stderr=subprocess.STDOUT, check=True)
            assert marker.encode() not in embedded.read_bytes(), "Stale restored shader"
            assert marker.encode() not in archive.read_bytes(), "Stale restored archive"
            assert embedded.read_bytes() in archive.read_bytes(), "Restored archive differs from shader"
    result = {
        "passed": True,
        "cases": ["backdated kernel A-B-A", "backdated shared header A-B-A"],
        "ninja": ninja_receipt,
        "cmake_sha256": hashlib.sha256((source / "ggml-metal/CMakeLists.txt").read_bytes()).hexdigest(),
        "source_snapshot_id": os.environ.get("DEVFLOW_SOURCE_SNAPSHOT_ID"),
        "source_sha256": os.environ.get("DEVFLOW_CONTENT_SHA256"),
    }
    (output / "receipt.json").write_text(json.dumps(result, indent=2) + "\n")
    print(json.dumps(result))


temporary = tempfile.mkdtemp(prefix="fixture-", dir=output)
try:
    verify(temporary)
except Exception:
    print("Failed fixture retained: " + str(Path(temporary).resolve()))
    raise
else:
    shutil.rmtree(temporary)
